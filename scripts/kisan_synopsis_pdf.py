    "Kisan Seva is a voice-based AI web assistant that delivers agricultural advisory "
    "services through simple spoken conversation. The farmer speaks a question in "
    "English, Hindi, or Kannada; the system converts the speech to text, understands "
    "its intent using Artificial Intelligence and Natural Language Processing (NLP), "
    "and replies with a short, spoken answer. It targets the three most urgent farming "
