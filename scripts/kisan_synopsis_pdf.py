def h1(text):
    return [CondPageBreak(H1_ORPHAN), Paragraph(f"<b>{text}</b>", h1_style)]


def section(story, num_title, first_flowable):
    """Heading kept together with its first flowable."""
    head = h1(num_title)
    story.extend(head)
    story.append(first_flowable)


def base_table_style(n_rows, header=True):
    cmds = [
        ("GRID", (0, 0), (-1, -1), 0.6, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 3.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3.5),
    ]
    if header:
        cmds.append(("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL))
        for r in range(1, n_rows):
            cmds.append(("BACKGROUND", (0, r), (-1, r),
                         TABLE_STRIPE if r % 2 == 0 else colors.white))
    return cmds


def footer(canvas, doc):
    canvas.saveState()
