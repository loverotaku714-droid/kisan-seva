function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
function hasWord(q, word) {
  const norm = q.replace(/[^\p{L}\p{N}\p{M}]+/gu, " ");
  if (word.endsWith("*")) {
    return new RegExp(`(^|\\s)${escapeRe(word.slice(0, -1))}`).test(norm);
  }
  return ` ${norm} `.includes(` ${word} `);
}
